// "Making of" archive: every generated image worth keeping (doctor captures, shot contact sheets,
// concept art, asset sheets, gameplay shots) is copied into making-of/<milestone>/ and recorded in
// making-of/index.json with its milestone, kind, caption and whether it is a chapter highlight.
// Usage:
//   node tools/harness/cli.mjs making-of add <file> --milestone M2 --kind screenshot --caption "..." [--highlight] [--slug name]
//   node tools/harness/cli.mjs making-of list [--milestone M2]
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, extname } from "node:path";
import { ROOT } from "./lib.mjs";

const DIR = ROOT + "making-of/";
const INDEX = DIR + "index.json";
export const KINDS = ["concept", "screenshot", "contact-sheet", "asset-sheet", "asset-thumb", "comparison", "diagram"];
const MILESTONE = /^(M\d{1,2}|A\d|B\d{1,3}|run)$/;

function load() {
  try {
    return JSON.parse(readFileSync(INDEX, "utf8"));
  } catch {
    return { $comment: "Generated by tools/harness/makingof.mjs. One entry per archived image, oldest first.", entries: [] };
  }
}

const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 48);

/** Copy an image into the archive and index it. Returns the archive-relative path. */
export function archive(file, { milestone, kind, caption, highlight = false, slug, source }) {
  const abs = existsSync(file) ? file : ROOT + file;
  if (!existsSync(abs)) throw new Error(`no such file: ${file}`);
  if (!MILESTONE.test(milestone ?? "")) throw new Error(`--milestone must look like M3, A1, B12 or run (got ${milestone})`);
  if (!KINDS.includes(kind)) throw new Error(`--kind must be one of ${KINDS.join(", ")}`);
  if (!caption) throw new Error("--caption is required (one sentence, what this image shows)");
  const now = new Date();
  const stamp = now.toISOString().slice(0, 16).replace(/[-:]/g, "").replace("T", "-");
  const name = `${stamp}_${slugify(slug ?? basename(abs, extname(abs)))}${extname(abs).toLowerCase()}`;
  const folder = `${milestone.toLowerCase()}/`;
  mkdirSync(DIR + folder, { recursive: true });
  copyFileSync(abs, DIR + folder + name);
  const idx = load();
  const entry = { file: folder + name, milestone, kind, caption, highlight: Boolean(highlight), when: now.toISOString(), source: source ?? file.replace(ROOT, "").replace(/\\/g, "/"), bytes: statSync(abs).size };
  idx.entries.push(entry);
  writeFileSync(INDEX, JSON.stringify(idx, null, 2) + "\n");
  return entry.file;
}

export function makingOfCmd(out, args) {
  const sub = args._[0];
  if (sub === "add") {
    const file = args._[1];
    const p = archive(file, { milestone: args.milestone, kind: args.kind, caption: args.caption, highlight: args.highlight === true, slug: args.slug });
    out.line(`archived ${p}`);
    return out.finish("PASS");
  }
  if (sub === "list") {
    const idx = load();
    const rows = idx.entries.filter((e) => !args.milestone || e.milestone === args.milestone);
    for (const e of rows.slice(-12)) out.line(`${e.milestone} ${e.kind}${e.highlight ? " *" : ""} ${e.file}  ${e.caption.slice(0, 70)}`);
    const mb = idx.entries.reduce((a, e) => a + (e.bytes ?? 0), 0) / 1e6;
    out.line(`${idx.entries.length} images, ${mb.toFixed(1)} MB total`);
    return out.finish("PASS");
  }
  out.line("usage: making-of add <file> --milestone M2 --kind screenshot --caption \"...\" [--highlight] | making-of list [--milestone M2]");
  return out.finish("FAIL", "1 (bad subcommand)");
}
